import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

function replace(source, before, after, label) {
  if (!source.includes(before)) throw new Error(`Terminal entity generation cannot find ${label}`);
  return source.replace(before, after);
}

export async function generateTerminalEntities({ rawDirectory, outputRoot }) {
  let agentRun = await readFile(join(rawDirectory, "agent_runs.rs"), "utf8");
  agentRun = replace(agentRun, "//! `SeaORM` Entity, @generated by sea-orm-codegen\n\n", "", "Agent Run banner");
  agentRun = replace(agentRun, "pub ticket_seq: Option<i64>", "pub ticket_seq: Option<i32>", "Agent Run ticket sequence type");
  agentRun = replace(agentRun, "pub exit_code: Option<i64>", "pub exit_code: Option<i32>", "Agent Run exit code type");
  for (const field of ["error", "cwd", "design_dir"]) {
    agentRun = replace(agentRun, "    #[sea_orm(column_type = \"Text\", nullable)]\n", "", `Agent Run ${field} SQLite annotation`);
  }
  agentRun = replace(agentRun, "    pub cwd: Option<String>,", "    #[seaography(ignore)]\n    pub cwd: Option<String>,", "Agent Run cwd protection");
  agentRun = replace(agentRun, "    pub design_dir: Option<String>,", "    #[seaography(ignore)]\n    pub design_dir: Option<String>,", "Agent Run design directory protection");
  agentRun = replace(
    agentRun,
    "    #[sea_orm(has_one)]\n    pub agent_terminal_sessions: HasOne<super::agent_terminal_sessions::Entity>,",
    "    #[sea_orm(belongs_to, from = \"issue_id\", to = \"id\")]\n    pub issue: BelongsTo<crate::work_management::issue::Entity>,",
    "Agent Run relation policy",
  );

  let session = await readFile(join(rawDirectory, "agent_terminal_sessions.rs"), "utf8");
  session = replace(session, "//! `SeaORM` Entity, @generated by sea-orm-codegen\n\n", "", "Terminal Session banner");
  session = replace(session, "    #[sea_orm(column_type = \"Text\", nullable)]\n", "", "Terminal Session document path SQLite annotation");
  for (const field of [
    "tmux_session_name",
    "runtime_cleanup_pending",
    "runtime_namespace",
    "output_identity",
    "output_sequence",
    "last_output_at",
  ]) {
    session = replace(
      session,
      `    pub ${field}:`,
      `    #[seaography(ignore)]\n    pub ${field}:`,
      `Terminal Session ${field} protection`,
    );
  }
  session = replace(
    session,
    "    #[sea_orm(\n        belongs_to,\n        from = \"agent_run_id\",\n        to = \"id\",\n        on_update = \"NoAction\",\n        on_delete = \"Cascade\"\n    )]\n    pub agent_runs: BelongsTo<super::agent_runs::Entity>,",
    "    #[sea_orm(belongs_to, from = \"agent_run_id\", to = \"id\")]\n    pub agent_run: BelongsTo<crate::runs::agent_run::Entity>,",
    "Terminal Session Agent Run relation policy",
  );

  const target = join(outputRoot, "terminal-entities");
  await mkdir(target, { recursive: true });
  await writeFile(join(target, "agent_run.rs"), agentRun, "utf8");
  await writeFile(join(target, "session.rs"), session, "utf8");
}
