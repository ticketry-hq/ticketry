test("empty Sprints opens by Plan button and keyboard, and a failed graph read recovers on reload", { tag: "@case-workspace-empty-read-recovery" }, async ({ page, request }) => {
  await moduleFixture(request, "Navigation");
  await page.goto("/");
  await page.getByTestId("workspace-tab-plan").click();
  await expect(page.getByTestId("sprints-list")).toBeVisible();
  await expect(page.getByRole("button", { name: "New sprint", exact: true })).toBeVisible();
  await expect(page.locator('[data-testid^="sprint-card-"]')).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(page.getByTestId("workspace-tab-plan")).toBeFocused();
  await page.keyboard.press("Space");
  await expect(page.getByTestId("sprints-list")).toBeVisible();
  await page.route("**/graphql", async (route) => {
    if (route.request().postDataJSON()?.operationName === "PlanningGraph") return route.fulfill({ json: { errors: [{ message: "Planning read unavailable" }] } });
    return route.continue();
  });
  await page.reload();
  await page.getByTestId("workspace-tab-plan").click();
  await expect(page.getByRole("alert").filter({ hasText: "Planning read unavailable" })).toBeVisible();
  await page.unroute("**/graphql");
  await page.reload();
  await page.getByTestId("workspace-tab-plan").click();
  await expect(page.getByTestId("sprints-list")).toBeVisible();
  await expect(page.locator('[data-testid^="sprint-card-"]')).toHaveCount(0);
});


test("Review in Plan opens the explicit sprint after leaving and reentering a running discovery visit", { tag: "@case-workspace-review-entry" }, async ({ page, request }) => {
  const fixture = await moduleFixture(request, "ReviewEntry");
  const first = await sprintThroughUi(page, fixture, "ReviewEntry oldest");
  const second = await createSprint(page, "ReviewEntry target");
  await addGoal(second.card, "Open the correct review visit");
  await providerMode("success", false, { prefix: fixture.prefix });
  const execution = await launchFromCard(page, second.card, request, second.id, "Find stories for these goals");
  await second.card.getByRole("button", { name: "Plan", exact: true }).click();
  await expect(page.getByTestId("plan-sprint").getByRole("heading", { name: "ReviewEntry target", exact: true, level: 1 })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByTestId("workspace-tab-plan")).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.getByTestId("plan-sprint").getByRole("heading", { name: "ReviewEntry oldest", exact: true, level: 1 })).toBeVisible();
  await page.getByRole("button", { name: "Back to sprints", exact: true }).click();
  await expect(second.card.getByRole("status")).toHaveText("An agent is looking for stories…");
  await releaseProvider(execution.id);
  await expect(second.card.getByText(/4 suggestions ready/)).toBeVisible();
  await executionCleaned(execution.id);
  await second.card.getByRole("button", { name: "Review in Plan →" }).click();
  await expect(page.getByTestId("plan-sprint").getByRole("heading", { name: "ReviewEntry target", exact: true, level: 1 })).toBeVisible();
  expect((await suggestions(request, second.id)).filter((row) => row.status === "waiting")).toHaveLength(4);
  expect(await suggestions(request, first.id)).toEqual([]);
});

