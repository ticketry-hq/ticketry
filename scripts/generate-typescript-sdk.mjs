import {
  cpSync,
  existsSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";

const root = resolve(import.meta.dirname, "..");
const schema = resolve(
  root,
  process.env.WORKTRACKER_OPENAPI_SCHEMA || "openapi.json",
);
const config = resolve(
  root,
  "surfaces",
  "worktracker-typescript-sdk",
  "openapi-generator-config.json",
);
const destination = resolve(
  root,
  process.env.WORKTRACKER_GENERATED_DIR ||
    "surfaces/worktracker-typescript-sdk/src/generated",
);

if (!existsSync(schema)) {
  throw new Error("openapi.json is missing; run npm run openapi:export first");
}

const tempRoot = mkdtempSync(join(tmpdir(), "worktracker-openapi-generator-"));
const temp = resolve(tempRoot, "output");
const tempSchema = resolve(tempRoot, "openapi.json");
const tempConfig = resolve(tempRoot, "config.json");
cpSync(schema, tempSchema);
cpSync(config, tempConfig);
const cli = resolve(
  root,
  "node_modules",
  ".bin",
  process.platform === "win32" ? "openapi-generator-cli.cmd" : "openapi-generator-cli",
);
const brewJavaBin = "/opt/homebrew/opt/openjdk@17/bin";
const javaCommand = existsSync(resolve(brewJavaBin, "java"))
  ? resolve(brewJavaBin, "java")
  : "java";
const generatorEnv = existsSync(resolve(brewJavaBin, "java"))
  ? { ...process.env, PATH: `${brewJavaBin}:${process.env.PATH || ""}` }
  : process.env;

const generatorArgs = [
    "generate",
    "-g",
    "typescript-fetch",
    "-i",
    tempSchema,
    "-o",
    temp,
    "-c",
    tempConfig,
    "--global-property",
    "apis,models,supportingFiles=runtime.ts:index.ts",
];
const java = spawnSync(javaCommand, ["-version"], { encoding: "utf8" });
const javaVersion = `${java.stderr || ""}${java.stdout || ""}`.match(
  /version "(?:1\.)?(\d+)/,
);
if (!javaVersion || Number(javaVersion[1]) < 11) {
  throw new Error("OpenAPI generation requires Java 11 or later.");
}
const result = spawnSync(cli, generatorArgs, {
  cwd: root,
  stdio: "inherit",
  env: generatorEnv,
});
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);

rmSync(destination, { recursive: true, force: true });
cpSync(resolve(temp, "src", "apis"), resolve(destination, "apis"), {
  recursive: true,
});
cpSync(resolve(temp, "src", "models"), resolve(destination, "models"), {
  recursive: true,
});
cpSync(resolve(temp, "src", "runtime.ts"), resolve(destination, "runtime.ts"));
cpSync(resolve(temp, "src", "index.ts"), resolve(destination, "index.ts"));

const notice =
  "/* AUTO-GENERATED by npm run sdk:generate. DO NOT EDIT. */\n// @ts-nocheck\n";
const stamp = (directory) => {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) stamp(path);
    else if (entry.name.endsWith(".ts")) {
      const content = readFileSync(path, "utf8");
      const stamped = content.startsWith(notice) ? content : notice + content;
      writeFileSync(
        path,
        stamped.replace(/[ \t]+$/gm, "").replace(/\n*$/, "\n"),
      );
    }
  }
};
stamp(destination);

// OpenAPI Generator names an inline enum `StatusEnum` while it is unique, but
// prefixes both enums once ChatSession introduces a second `status` field.
// Preserve the already-published import without forking the generated model:
// the legacy name remains an exact alias of AutomationAttemptStatusEnum.
const generatedModels = resolve(destination, "models");
writeFileSync(
  resolve(generatedModels, "StatusEnum.ts"),
  notice
    + "export {\n"
    + "  AutomationAttemptStatusEnum as StatusEnum,\n"
    + "  instanceOfAutomationAttemptStatusEnum as instanceOfStatusEnum,\n"
    + "  AutomationAttemptStatusEnumFromJSON as StatusEnumFromJSON,\n"
    + "  AutomationAttemptStatusEnumFromJSONTyped as StatusEnumFromJSONTyped,\n"
    + "  AutomationAttemptStatusEnumToJSON as StatusEnumToJSON,\n"
    + "  AutomationAttemptStatusEnumToJSONTyped as StatusEnumToJSONTyped,\n"
    + "} from './AutomationAttemptStatusEnum.js';\n",
);
const generatedModelsIndex = resolve(generatedModels, "index.ts");
const generatedModelsIndexContents = readFileSync(generatedModelsIndex, "utf8");
if (!generatedModelsIndexContents.includes("'./StatusEnum.js'")) {
  writeFileSync(
    generatedModelsIndex,
    generatedModelsIndexContents.replace(/\n*$/, "\n")
      + "export * from './StatusEnum.js';\n",
  );
}
rmSync(tempRoot, { recursive: true, force: true });
