import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

function replace(source, before, after, label) {
  if (!source.includes(before)) {
    throw new Error(`Execution entity generation cannot find ${label}`);
  }
  return source.replace(before, after);
}

function dateColumn(source, field) {
  return replace(
    source,
    `    #[sea_orm(ignore, column_type = "custom(\\"datetime\\")", select_as = "text")]\n    pub ${field}: String,`,
    `    pub ${field}: DateTime,`,
    `${field} datetime mapping`,
  );
}

export async function generateExecutionEntities({ rawDirectory, outputRoot }) {
  let graphRun = await readFile(join(rawDirectory, "graph_runs.rs"), "utf8");
  graphRun = replace(graphRun, "//! `SeaORM` Entity, @generated by sea-orm-codegen\n\n", "", "Graph Run banner");
  graphRun = replace(
    graphRun,
    "use sea_orm::entity::prelude::*;\n",
    "use sea_orm::entity::prelude::*;\n\nuse crate::work_management::{issue, project};\n",
    "Graph Run relation imports",
  );
  graphRun = dateColumn(dateColumn(graphRun, "created_at"), "updated_at");
  graphRun = replace(
    graphRun,
    "    #[sea_orm(column_type = \"Text\", nullable)]\n    pub launch_configuration: Option<String>,",
    "    #[seaography(ignore)]\n    pub launch_configuration: Option<String>,",
    "Graph Run policy protection",
  );
  graphRun = graphRun.slice(0, graphRun.indexOf("    #[sea_orm(has_many)]")) + `    #[sea_orm(belongs_to, relation_enum = "Root", from = "root_id", to = "id")]\n    pub root: BelongsTo<issue::Entity>,\n    #[sea_orm(belongs_to, relation_enum = "Module", from = "module_id", to = "id")]\n    pub module: BelongsTo<Option<issue::Entity>>,\n    #[sea_orm(belongs_to, from = "project_id", to = "id")]\n    pub project: BelongsTo<project::Entity>,\n}\n\nimpl ActiveModelBehavior for ActiveModel {}\n`;

  let launchClaim = await readFile(join(rawDirectory, "launched_tasks.rs"), "utf8");
  launchClaim = replace(launchClaim, "//! `SeaORM` Entity, @generated by sea-orm-codegen\n\n", "", "launch claim banner");
  launchClaim = dateColumn(launchClaim, "launched_at");
  for (const field of ["claim_id", "launch_effect_id"]) {
    launchClaim = replace(
      launchClaim,
      `    pub ${field}: String,`,
      `    #[seaography(ignore)]\n    pub ${field}: String,`,
      `launch claim ${field} protection`,
    );
  }
  launchClaim = replace(
    launchClaim,
    "    pub agent_run_id: String,",
    "    #[seaography(ignore)]\n    pub agent_run_id: String,",
    "launch claim Agent Run protection",
  );
  launchClaim = launchClaim.slice(0, launchClaim.indexOf("    #[sea_orm(\n        belongs_to,")) + `    #[sea_orm(belongs_to, from = "task_id", to = "id")]\n    pub task: BelongsTo<crate::work_management::issue::Entity>,\n    #[sea_orm(belongs_to, from = "root_id", to = "root_id")]\n    pub graph_run: BelongsTo<super::graph_run::Entity>,\n    #[sea_orm(belongs_to, from = "agent_run_id", to = "id")]\n    pub agent_run: BelongsTo<crate::runs::agent_run::Entity>,\n}\n\nimpl ActiveModelBehavior for ActiveModel {}\n`;

  const target = join(outputRoot, "execution-entities");
  await mkdir(target, { recursive: true });
  await writeFile(join(target, "graph_run.rs"), graphRun, "utf8");
  await writeFile(join(target, "launch_claim.rs"), launchClaim, "utf8");
}
