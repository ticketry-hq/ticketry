featureSuite("story-moves", { test, isolation: "case" }, () => {
test("manual moves support buttons, keyboard, drag, optimistic rollback, Retry and Undo", { tag: ["@case-manual-moves"] }, async ({ page, request }, info) => {
  const fixture = await moduleFixture(request, "Moves");
  const existing = fixture.stories.find((row) => row.name === "Moves existing")!;
  await createWorkItem(request, fixture.projectId, { name: "Moves nested", issue_type_id: fixture.storyType.id, parent_id: existing.id });
  const { id } = await emptyVisit(page, fixture, "Moves release");
  await selectEpic(page, fixture.epic.name);
  const backlog = page.getByTestId("plan-backlog");
  const sprint = page.getByTestId("plan-sprint-items");
  const row = () => storyRow(backlog, existing.name);
  const membership = async () => (await storyNamed(request, fixture.projectId, existing.name))?.sprintId;
  await expect(storyRow(backlog, "Moves nested")).toHaveCount(0);
  await row().getByRole("button", { name: /^Plan .+ into sprint$/ }).click();
  await expect.poll(membership).toBe(id);
  await page.getByTestId("plan-undo").click();
  await expect.poll(membership).toBeNull();
  await row().locator("[data-plan-story]").press("Alt+ArrowDown");
  await expect.poll(membership).toBe(id);
  await expect(storyRow(backlog, "Moves waiting").getByRole("button", { name: /^Plan / })).toBeFocused();
  await storyRow(sprint, existing.name).locator("[data-plan-story]").press("Alt+ArrowUp");
  await expect.poll(membership).toBeNull();
  await selectEpic(page, fixture.secondEpic.name);
  await storyRow(backlog, fixture.other.name).getByRole("button", { name: /^Plan / }).click();
  await expect.poll(async () => (await storyNamed(request, fixture.projectId, fixture.other.name))?.sprintId).toBe(id);
  await selectEpic(page, fixture.epic.name);
  await expect(storyRow(sprint, fixture.other.name).locator("xpath=..")).toHaveClass(/opacity-50/);
  await storyRow(sprint, fixture.other.name).getByRole("button", { name: /^Return / }).click();
  await expect.poll(async () => (await storyNamed(request, fixture.projectId, fixture.other.name))?.sprintId).toBeNull();
  await row().dragTo(sprint);
  await expect.poll(membership).toBe(id);
  await storyRow(sprint, existing.name).dragTo(backlog);
  await expect.poll(membership).toBeNull();
  let reject = true;
  await page.route("**/graphql", async (route) => {
    if (reject && route.request().postDataJSON()?.operationName === "PlanWorkItem") {
      reject = false;
      return route.abort("failed");
    }
    return route.continue();
  });
  await row().getByRole("button", { name: /^Plan / }).click();
  await expect(page.getByTestId("plan-feedback")).toContainText("Couldn't move");
  await expect(row()).toBeVisible();
  expect(await membership()).toBeNull();
  await page.getByRole("button", { name: /^Retry moving .+ to Moves release$/ }).click();
  await expect.poll(membership).toBe(id);
  await page.getByTestId("plan-undo").click();
  await expect.poll(membership).toBeNull();
  reject = true;
  await row().getByRole("button", { name: /^Plan / }).click();
  await expect(page.getByTestId("plan-feedback")).toContainText("Couldn't move");
  await page.getByRole("button", { name: /^Dismiss .+ failure$/ }).click();
  await expect(page.getByRole("button", { name: /^Retry moving / })).toHaveCount(0);
  expect(await membership()).toBeNull();
  await page.unroute("**/graphql");
  let release = () => {};
  const gate = new Promise<void>((resolve) => { release = resolve; });
  await page.route("**/graphql", async (route) => {
    if (route.request().postDataJSON()?.operationName !== "PlanWorkItem") return route.continue();
    const response = await route.fetch();
    await gate;
    return route.fulfill({ response });
  });
  await row().getByRole("button", { name: /^Plan / }).click();
  const pending = storyRow(sprint, existing.name);
  await expect(pending).toHaveAttribute("aria-busy", "true");
  await expect(pending).toHaveAttribute("draggable", "false");
  await expect(pending.getByRole("button", { name: /^Return / })).toBeDisabled();
  release();
  await expect(pending).toHaveAttribute("aria-busy", "false");
  await page.unroute("**/graphql");
  await reloadPlan(page, "Moves release", fixture.epic.name);
  await expect(storyRow(sprint, existing.name)).toBeVisible();
  expect(await membership()).toBe(id);
  await page.setViewportSize({ width: 390, height: 844 });
  const returnButton = storyRow(sprint, existing.name).getByRole("button", { name: /^Return / });
  await returnButton.scrollIntoViewIfNeeded();
  await returnButton.focus();
  await expect(returnButton).toBeFocused();
  await expect(returnButton).toBeInViewport();
  await page.screenshot({ path: info.outputPath("moves-narrow.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test("closed-sprint move eligibility rejects buttons keyboard and drag but permits outgoing work", { tag: ["@case-moves-closed-sprint"] }, async ({ page, context, request }) => {
  const fixture = await moduleFixture(request, "Eligibility");
  const current = await sprintThroughUi(page, fixture, "Eligibility release");
  const doneState = fixture.catalog.states.nodes.find((row) => row.group === "completed")!;
  const done = await stateFixture(request, fixture, "Eligibility done", doneState.id, fixture.epic.id);
  await graphql(request, PlanWorkItemDocument, { id: done.id, sprintId: current.id });
  await reopenSprints(page);
  await openSprint(page, "Eligibility release");
  await selectEpic(page, fixture.epic.name);
  const sprint = page.getByTestId("plan-sprint-items");
  const backlog = page.getByTestId("plan-backlog");
  await storyRow(backlog, "Eligibility existing").getByRole("button", { name: /^Plan / }).click();
  await expect(storyRow(sprint, "Eligibility existing")).toBeVisible();
  const other = await context.newPage();
  await other.routeWebSocket((url) => url.pathname === "/" && url.searchParams.has("token"), () => {});
  await other.goto("/");
  await other.getByTestId("workspace-tab-plan").click();
  await expect(other.getByTestId("plan-sprint").or(other.getByTestId("sprints-list"))).toBeVisible();
  if (await other.getByRole("button", { name: "Back to sprints" }).count()) await other.getByRole("button", { name: "Back to sprints" }).click();
  const card = cardNamed(other, "Eligibility release");
  await card.getByRole("button", { name: "Start", exact: true }).click();
  await other.getByRole("dialog").getByRole("button", { name: "Start sprint", exact: true }).click();
  await card.getByRole("button", { name: "Complete", exact: true }).click();
  await other.getByRole("dialog").getByRole("button", { name: "Complete sprint", exact: true }).click();
  await expect.poll(async () => (await sprintState(request, current.id))?.status).toBe("completed");
  await expect(storyRow(backlog, "Eligibility waiting").getByRole("button", { name: /^Plan / })).toBeDisabled();
  await expect(backlog.getByRole("button", { name: "Add story", exact: true })).toBeDisabled();
  await expect(sprint.getByRole("button", { name: "Add story", exact: true })).toBeDisabled();
  const blocked = storyRow(backlog, "Eligibility waiting");
  await expect(blocked).toHaveAttribute("draggable", "false");
  await blocked.locator("[data-plan-story]").press("Alt+ArrowDown");
  await blocked.dragTo(sprint);
  expect((await storyNamed(request, fixture.projectId, "Eligibility waiting"))?.sprintId).toBeNull();
  await storyRow(sprint, "Eligibility done").getByRole("button", { name: /^Return / }).click();
  await expect.poll(async () => (await storyNamed(request, fixture.projectId, done.name))?.sprintId).toBeNull();
  await expect(page.getByTestId("plan-undo")).toBeDisabled();
  await expect(page.getByTestId("plan-undo-hint")).toHaveText("This sprint is completed and closed to new work.");
  await other.close();
});

test("empty move panes and final-row keyboard focus survive a reload", { tag: "@case-moves-empty-focus" }, async ({ page, request }) => {
  const fixture = await moduleFixture(request, "EmptyMoves");
  const current = await emptyVisit(page, fixture, "EmptyMoves release");
  await selectEpic(page, fixture.secondEpic.name);
  const backlog = page.getByTestId("plan-backlog");
  const sprint = page.getByTestId("plan-sprint-items");
  await expect(sprint.getByText("Nothing planned yet. Pick an epic, then use + or drag a story here.")).toBeVisible();
  await storyRow(backlog, fixture.other.name).locator("[data-plan-story]").press("Alt+ArrowDown");
  await expect.poll(async () => (await storyNamed(request, fixture.projectId, fixture.other.name))?.sprintId).toBe(current.id);
  await expect(backlog.getByText(`Nothing unplanned in ${fixture.secondEpic.name}.`)).toBeVisible();
  await expect(backlog.getByRole("heading", { name: "Backlog", exact: true })).toBeFocused();
  await storyRow(sprint, fixture.other.name).locator("[data-plan-story]").press("Alt+ArrowUp");
  await expect.poll(async () => (await storyNamed(request, fixture.projectId, fixture.other.name))?.sprintId).toBeNull();
  await expect(sprint.getByRole("heading", { name: "EmptyMoves release", exact: true })).toBeFocused();
  await reloadPlan(page, "EmptyMoves release", fixture.secondEpic.name);
  await expect(storyRow(backlog, fixture.other.name)).toBeVisible();
  await expect(sprint.getByText("Nothing planned yet. Pick an epic, then use + or drag a story here.")).toBeVisible();
});

});
