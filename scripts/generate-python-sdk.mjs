import {
  cpSync,
  existsSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";

const root = resolve(import.meta.dirname, "..");
const schema = resolve(
  root,
  process.env.WORKTRACKER_OPENAPI_SCHEMA || "openapi.json",
);
const destination = resolve(
  root,
  process.env.WORKTRACKER_PYTHON_GENERATED_DIR ||
    "surfaces/worktracker-sdk/worktracker_sdk/generated",
);

if (!existsSync(schema)) {
  throw new Error("openapi.json is missing; run npm run openapi:export first");
}

const tempRoot = mkdtempSync(join(tmpdir(), "worktracker-python-generator-"));
const temp = resolve(tempRoot, "output");
const tempSchema = resolve(tempRoot, "openapi.json");
cpSync(schema, tempSchema);

const cli = resolve(
  root,
  "node_modules",
  ".bin",
  process.platform === "win32" ? "openapi-generator-cli.cmd" : "openapi-generator-cli",
);
const generatorJar = resolve(root, ".openapi-generator", "7.23.0.jar");
const brewJavaBin = "/opt/homebrew/opt/openjdk@17/bin";
const javaCommand = existsSync(resolve(brewJavaBin, "java"))
  ? resolve(brewJavaBin, "java")
  : "java";
const generatorEnv = existsSync(resolve(brewJavaBin, "java"))
  ? { ...process.env, PATH: `${brewJavaBin}:${process.env.PATH || ""}` }
  : process.env;

const generatorArgs = [
  "generate",
  "-g",
  "python",
  "-i",
  tempSchema,
  "-o",
  temp,
  "--additional-properties",
  "packageName=worktracker_sdk,packageVersion=0.1.0,projectName=worktracker-sdk",
  "--global-property",
  "apis,models,supportingFiles=api_client.py:api_response.py:configuration.py:exceptions.py:rest.py:__init__.py",
];
const java = spawnSync(javaCommand, ["-version"], { encoding: "utf8" });
const javaVersion = `${java.stderr || ""}${java.stdout || ""}`.match(
  /version "(?:1\.)?(\d+)/,
);
const useDocker =
  process.env.OPENAPI_GENERATOR_USE_DOCKER === "1" ||
  !javaVersion ||
  Number(javaVersion[1]) < 11;
const localGenerator = existsSync(cli)
  ? [cli, generatorArgs]
  : [javaCommand, ["-jar", generatorJar, ...generatorArgs]];
const result = useDocker
  ? spawnSync(
      "docker",
      [
        "run",
        "--rm",
        "-v",
        `${tempRoot}:/local`,
        "openapitools/openapi-generator-cli:v7.23.0",
        ...generatorArgs.map((arg) => arg.replace(tempRoot, "/local")),
      ],
      { cwd: root, stdio: "inherit" },
    )
  : spawnSync(localGenerator[0], localGenerator[1], {
      cwd: root,
      stdio: "inherit",
      env: generatorEnv,
    });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);

rmSync(destination, { recursive: true, force: true });
cpSync(resolve(temp, "worktracker_sdk"), destination, { recursive: true });

const notice =
  "# AUTO-GENERATED by npm run python-sdk:generate. DO NOT EDIT.\n";
const relocateAndStamp = (directory) => {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) relocateAndStamp(path);
    else if (entry.name.endsWith(".py")) {
      const content = readFileSync(path, "utf8")
        .replaceAll("worktracker_sdk.", "worktracker_sdk.generated.")
        .replaceAll(
          "from worktracker_sdk import rest",
          "from worktracker_sdk.generated import rest",
        )
        // Operations already carry the /work-tracker segment, so the SDK wants
        // the /api root. Callers configure either form, so strip a trailing
        // /work-tracker rather than doubling it. Both assignment paths need
        // this: the `host` setter, and the constructor, which writes
        // _base_path directly and never calls that setter.
        .replace(
          "self._base_path = value",
          "self._base_path = value.rstrip('/')\n        if self._base_path.endswith('/work-tracker'):\n            self._base_path = self._base_path[:-len('/work-tracker')]",
        )
        .replace(
          'self._base_path = "/api" if host is None else host',
          'self._base_path = "/api" if host is None else host.rstrip(\'/\')\n        if self._base_path.endswith(\'/work-tracker\'):\n            self._base_path = self._base_path[:-len(\'/work-tracker\')]',
        )
        // OpenAPI Generator 7.23 emits invalid Python for an enum whose sole
        // value is null. The nullable owning field already maps to Optional,
        // so this placeholder only needs to remain importable.
        .replace("class NullEnum(, Enum):", "class NullEnum(Enum):")
        .split("\n")
        .map((line) => line.trimEnd())
        .join("\n")
        .replace(/\n*$/, "\n");
      writeFileSync(path, notice + content);
    }
  }
};
relocateAndStamp(destination);
rmSync(tempRoot, { recursive: true, force: true });
