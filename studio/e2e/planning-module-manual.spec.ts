test("workspace, epic visits and inline Story creation work by keyboard and persist", { tag: ["@plan-workspace", "@plan-epics", "@plan-create", "@case-workspace-create"] }, async ({ page, request }, info) => {
  const fixture = await moduleFixture(request, "Manual");
  await selectModuleForProfile(request, fixture.projectId, fixture.epic.id, process.env.TICKETRY_E2E_DATA_DIR);
  const { id } = await emptyVisit(page, fixture, "Manual release");
  const backlog = page.getByTestId("plan-backlog");
  const sprint = page.getByTestId("plan-sprint-items");
  await expect(page.getByTestId("modules-pane-toggle")).toHaveCount(0);
  const first = await selectEpic(page, fixture.epic.name);
  await expect(first).toHaveAccessibleName("Manual epic, 2 backlog stories");
  const second = await selectEpic(page, fixture.secondEpic.name);
  await expect(second).toHaveAccessibleName("Manual other epic, 1 backlog stories");
  await second.press("Alt+BracketLeft");
  await expect(first).toHaveAttribute("aria-selected", "true");
  await first.press("Alt+BracketRight");
  await expect(second).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "Next epic", exact: true }).click();
  await expect(first).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: /^Done with Manual epic/ }).click();
  await expect(second).toHaveAttribute("aria-selected", "true");
  await expect(second).toBeFocused();
  await page.getByRole("button", { name: "Close Manual other epic", exact: true }).click();
  await expect(page.getByRole("button", { name: "Add epic", exact: true })).toBeFocused();
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByTestId("sprints-list")).toBeVisible();
  await page.locator('[data-testid^="sprint-card-"]').filter({ has: page.getByRole("heading", { name: "Manual release", exact: true }) })
    .getByRole("button", { name: "Plan", exact: true }).click();
  await expect(backlog.getByText("No epic open. Use + Add epic to plan another one.")).toBeVisible();
  await page.getByRole("button", { name: "Add epic", exact: true }).click();
  await page.getByRole("button", { name: "+ New epic", exact: true }).click();
  await page.getByRole("textbox", { name: "New epic name" }).fill("Discarded epic");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("textbox", { name: "New epic name" })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "Add epic", exact: true })).toHaveAttribute("aria-expanded", "false");
  await expect(page.getByTestId("plan-sprint")).toBeVisible();
  expect(await epicNamed(request, fixture.projectId, "Discarded epic")).toBeUndefined();
  await page.getByRole("button", { name: "Add epic", exact: true }).click();
  await page.getByRole("button", { name: "+ New epic", exact: true }).click();
  await page.getByRole("textbox", { name: "New epic name" }).fill("Manual created epic");
  await page.getByRole("textbox", { name: "New epic name" }).press("Enter");
  const createdTab = page.getByRole("tab", { name: /^Manual created epic,/ });
  await expect(createdTab).toHaveAttribute("aria-selected", "true");
  await expect(createdTab).toBeFocused();
  await backlog.getByRole("button", { name: "Add story", exact: true }).click();
  await backlog.getByRole("textbox", { name: "Story title" }).fill("Discarded Story");
  await page.keyboard.press("Escape");
  await expect(backlog.getByRole("textbox", { name: "Story title" })).toHaveCount(0);
  expect(await storyNamed(request, fixture.projectId, "Discarded Story")).toBeUndefined();
  await inlineStory(backlog, "  Manual new backlog  ");
  await backlog.getByRole("textbox", { name: "Story title" }).fill("Manual unsaved backlog draft");
  await inlineStory(sprint, "Manual new planned");
  const createdEpic = await epicNamed(request, fixture.projectId, "Manual created epic");
  expect(createdEpic).toBeTruthy();
  await selectModuleForProfile(request, fixture.projectId, createdEpic!.id, process.env.TICKETRY_E2E_DATA_DIR);
  expect(await storyNamed(request, fixture.projectId, "Manual new backlog")).toMatchObject({ parentId: createdEpic?.id, sprintId: null });
  expect(await storyNamed(request, fixture.projectId, "Manual new planned")).toMatchObject({ parentId: createdEpic?.id, sprintId: id });
  await expect(backlog.getByRole("textbox", { name: "Story title" })).toHaveValue("Manual unsaved backlog draft");
  expect(await storyNamed(request, fixture.projectId, "Manual unsaved backlog draft")).toBeUndefined();
  await expect(sprint.getByRole("textbox", { name: "Story title" })).toBeFocused();
  await backlog.getByRole("textbox", { name: "Story title" }).fill("");
  await storyRow(backlog, "Manual new backlog").locator("[data-plan-story]").press("Enter");
  await expect(page.getByRole("complementary", { name: "Selected ticket" }).getByTestId("issue-name")).toContainText("Manual new backlog");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("complementary", { name: "Selected ticket" })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(page.getByTestId("workspace-tab-plan")).toBeFocused();
  // Load the disposable module-folder fixtures before entering the module workspace.
  await page.reload();
  await page.getByRole("tab", { name: fixture.epic.name, exact: true }).last().click();
  await expect(page.getByTestId("workspace-tab-changes")).toBeEnabled();
  await page.getByTestId("workspace-tab-plan").focus();
  await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("button", { name: "Choose checkout" })).toBeVisible();
  await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  await expect(page.getByTestId("workspace-tab-changes")).toBeFocused();
  // Continue from the retained focus: locator.press() would refocus and mask theft.
  await page.keyboard.press("End");
  const lastModule = page.getByRole("tab", { name: "Manual created epic", exact: true }).last();
  await expect(lastModule).toHaveAttribute("aria-selected", "true");
  await expect(lastModule).toBeFocused();
  await page.keyboard.press("Home");
  await expect(page.getByTestId("workspace-tab-plan")).toBeFocused();
  await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("button", { name: "Choose checkout" })).toBeVisible();
  await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  await expect(page.getByTestId("workspace-tab-changes")).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.getByTestId("workspace-tab-changes")).toHaveAttribute("aria-selected", "true");
  await expect(page.getByRole("button", { name: "Choose checkout" })).toBeFocused();
  await page.getByTestId("workspace-tab-changes").focus();
  await page.keyboard.press("Space");
  await expect(page.getByRole("button", { name: "Choose checkout" })).toBeFocused();
  await page.getByTestId("workspace-tab-changes").focus();
  await page.keyboard.press("End");
  await expect(lastModule).toHaveAttribute("aria-selected", "true");
  await expect(lastModule).toBeFocused();
  await page.keyboard.press("Home");
  await expect(page.getByTestId("workspace-tab-plan")).toBeFocused();
  await reloadPlan(page, "Manual release", "Manual created epic");
  await expect(storyRow(backlog, "Manual new backlog")).toBeVisible();
  await expect(storyRow(sprint, "Manual new planned")).toBeVisible();
  await page.screenshot({ path: info.outputPath("manual-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await sprint.getByRole("button", { name: "Add story", exact: true }).scrollIntoViewIfNeeded();
  await sprint.getByRole("button", { name: "Add story", exact: true }).click();
  await expect(sprint.getByRole("textbox", { name: "Story title" })).toBeFocused();
  await expect(sprint.getByRole("textbox", { name: "Story title" })).toBeInViewport();
  await page.screenshot({ path: info.outputPath("manual-narrow.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test("manual moves support buttons, keyboard, drag, optimistic rollback, Retry and Undo", { tag: ["@plan-moves", "@plan-epics", "@case-manual-moves"] }, async ({ page, request }, info) => {
  const fixture = await moduleFixture(request, "Moves");
  const existing = fixture.stories.find((row) => row.name === "Moves existing")!;
  await createWorkItem(request, fixture.projectId, { name: "Moves nested", issue_type_id: fixture.storyType.id, parent_id: existing.id });
  const { id } = await emptyVisit(page, fixture, "Moves release");
  await selectEpic(page, fixture.epic.name);
  const backlog = page.getByTestId("plan-backlog");
  const sprint = page.getByTestId("plan-sprint-items");
  const row = () => storyRow(backlog, existing.name);
  const membership = async () => (await storyNamed(request, fixture.projectId, existing.name))?.sprintId;
  await expect(storyRow(backlog, "Moves nested")).toHaveCount(0);
  await row().getByRole("button", { name: /^Plan .+ into sprint$/ }).click();
  await expect.poll(membership).toBe(id);
  await page.getByTestId("plan-undo").click();
  await expect.poll(membership).toBeNull();
  await row().locator("[data-plan-story]").press("Alt+ArrowDown");
  await expect.poll(membership).toBe(id);
  await expect(storyRow(backlog, "Moves waiting").getByRole("button", { name: /^Plan / })).toBeFocused();
  await storyRow(sprint, existing.name).locator("[data-plan-story]").press("Alt+ArrowUp");
  await expect.poll(membership).toBeNull();
  await selectEpic(page, fixture.secondEpic.name);
  await storyRow(backlog, fixture.other.name).getByRole("button", { name: /^Plan / }).click();
  await expect.poll(async () => (await storyNamed(request, fixture.projectId, fixture.other.name))?.sprintId).toBe(id);
  await selectEpic(page, fixture.epic.name);
  await expect(storyRow(sprint, fixture.other.name).locator("xpath=..")).toHaveClass(/opacity-50/);
  await storyRow(sprint, fixture.other.name).getByRole("button", { name: /^Return / }).click();
  await expect.poll(async () => (await storyNamed(request, fixture.projectId, fixture.other.name))?.sprintId).toBeNull();
  await row().dragTo(sprint);
  await expect.poll(membership).toBe(id);
  await storyRow(sprint, existing.name).dragTo(backlog);
  await expect.poll(membership).toBeNull();
  let reject = true;
  await page.route("**/graphql", async (route) => {
    if (reject && route.request().postDataJSON()?.operationName === "PlanWorkItem") {
      reject = false;
      return route.abort("failed");
    }
    return route.continue();
  });
  await row().getByRole("button", { name: /^Plan / }).click();
  await expect(page.getByTestId("plan-feedback")).toContainText("Couldn't move");
  await expect(row()).toBeVisible();
  expect(await membership()).toBeNull();
  await page.getByRole("button", { name: /^Retry moving .+ to Moves release$/ }).click();
  await expect.poll(membership).toBe(id);
  await page.getByTestId("plan-undo").click();
  await expect.poll(membership).toBeNull();
  reject = true;
  await row().getByRole("button", { name: /^Plan / }).click();
  await expect(page.getByTestId("plan-feedback")).toContainText("Couldn't move");
  await page.getByRole("button", { name: /^Dismiss .+ failure$/ }).click();
  await expect(page.getByRole("button", { name: /^Retry moving / })).toHaveCount(0);
  expect(await membership()).toBeNull();
  await page.unroute("**/graphql");
  let release = () => {};
  const gate = new Promise<void>((resolve) => { release = resolve; });
  await page.route("**/graphql", async (route) => {
    if (route.request().postDataJSON()?.operationName !== "PlanWorkItem") return route.continue();
    const response = await route.fetch();
    await gate;
    return route.fulfill({ response });
  });
  await row().getByRole("button", { name: /^Plan / }).click();
  const pending = storyRow(sprint, existing.name);
  await expect(pending).toHaveAttribute("aria-busy", "true");
  await expect(pending).toHaveAttribute("draggable", "false");
  await expect(pending.getByRole("button", { name: /^Return / })).toBeDisabled();
  release();
  await expect(pending).toHaveAttribute("aria-busy", "false");
  await page.unroute("**/graphql");
  await reloadPlan(page, "Moves release", fixture.epic.name);
  await expect(storyRow(sprint, existing.name)).toBeVisible();
  expect(await membership()).toBe(id);
  await page.setViewportSize({ width: 390, height: 844 });
  const returnButton = storyRow(sprint, existing.name).getByRole("button", { name: /^Return / });
  await returnButton.scrollIntoViewIfNeeded();
  await returnButton.focus();
  await expect(returnButton).toBeFocused();
  await expect(returnButton).toBeInViewport();
  await page.screenshot({ path: info.outputPath("moves-narrow.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
