import { fireEvent, screen, waitFor } from "@testing-library/react";
import { expect, it } from "vitest";
import { editionAcceptanceFixture } from "./editionAcceptanceFixture";

it("[overhaul-622] covers Plan and Changes while preserving their mounted surface and active tab", async () => {
  const boundary = editionAcceptanceFixture();
  boundary.mount({ selectedTaskId: null });
  await screen.findByRole("button", { name: "Sprint: Sprint 24, Active" });
  const planTab = screen.getByTestId("workspace-tab-plan");
  fireEvent.click(planTab);
  await waitFor(() => expect(planTab).toHaveAttribute("aria-selected", "true"));
  const plan = await screen.findByTestId("plan-sprint");
  expect(plan).toBeVisible();
  fireEvent.click(screen.getByRole("button", { name: "Add epic" }));
  fireEvent.click(screen.getByRole("button", { name: "+ New epic" }));
  const draft = screen.getByRole("textbox", { name: "New epic name" });
  fireEvent.change(draft, { target: { value: "Keep this Plan draft" } });
  const footer = screen.getByRole("button", { name: "Open Module Manager" });
  fireEvent.mouseDown(footer);
  fireEvent.click(footer);
  expect(screen.getByRole("region", { name: "Module Manager" })).toBeVisible();
  expect(screen.getByTestId("workspace-tab-plan")).toBe(planTab);
  expect(screen.getByTestId("plan-sprint")).toBe(plan);
  expect(plan.closest("[inert]")).not.toBeNull();
  expect(screen.getByRole("textbox", { name: "New epic name", hidden: true })).toBe(draft);
  expect(draft).toHaveValue("Keep this Plan draft");
  expect(planTab).toHaveAttribute("aria-selected", "true");
  const search = screen.getByRole("searchbox", { name: "Search modules" });
  fireEvent.mouseDown(search);
  fireEvent.click(search);
  expect(screen.getByRole("textbox", { name: "New epic name", hidden: true })).toBe(draft);
  expect(draft).toHaveValue("Keep this Plan draft");
  fireEvent.keyDown(document.activeElement!, { key: "Escape" });
  await waitFor(() => expect(screen.queryByRole("region", { name: "Module Manager" })).toBeNull());
  expect(planTab).toHaveAttribute("aria-selected", "true");
  expect(screen.getByTestId("plan-sprint")).toBe(plan);
  expect(plan.closest("[inert]")).toBeNull();
  expect(plan).toBeVisible();
  expect(screen.getByRole("textbox", { name: "New epic name" })).toBe(draft);
  expect(draft).toHaveValue("Keep this Plan draft");
  const changesTab = screen.getByTestId("workspace-tab-changes");
  fireEvent.mouseDown(changesTab);
  expect(screen.queryByRole("textbox", { name: "New epic name" })).toBeNull();
  fireEvent.click(changesTab);
  const changes = await screen.findByTestId("independent-changes-workspace");
  expect(changes).toBeVisible();
  fireEvent.click(screen.getByRole("button", { name: "Open Module Manager" }));
  expect(screen.getByTestId("independent-changes-workspace")).toBe(changes);
  expect(changes.closest("[inert]")).not.toBeNull();
  expect(screen.getByTestId("workspace-tab-changes")).toBe(changesTab);
  expect(changesTab).toHaveAttribute("aria-selected", "true");
  fireEvent.keyDown(document.activeElement!, { key: "Escape" });
  await waitFor(() => expect(changes.closest("[inert]")).toBeNull());
  expect(changes).toBeVisible();
  expect(changesTab).toHaveAttribute("aria-selected", "true");
});
